CREATE VIEW order_totals AS
  SELECT customer_id, count(*) AS orders, sum(total) AS total FROM orders GROUP BY customer_id;

CREATE MATERIALIZED VIEW customer_stats AS
  SELECT c.id, c.name, count(o.id) AS orders, coalesce(sum(o.total), 0) AS spent
    FROM customers c LEFT JOIN orders o ON o.customer_id = c.id
   GROUP BY c.id, c.name;
CREATE UNIQUE INDEX customer_stats_id_idx ON customer_stats (id);

CREATE FUNCTION customer_total(cid integer) RETURNS numeric
  LANGUAGE sql STABLE
  AS $$ SELECT coalesce(sum(total), 0) FROM orders WHERE customer_id = cid $$;

CREATE PROCEDURE mark_shipped(order_id bigint)
  LANGUAGE plpgsql
  AS $$
BEGIN
  UPDATE orders SET status = 'shipped' WHERE id = order_id;
  RAISE NOTICE 'Order % shipped', order_id;
END
$$;

CREATE SCHEMA inventory;

CREATE TYPE inventory.unit AS ENUM ('piece', 'kg', 'litre');

CREATE TABLE inventory.products (
  sku text PRIMARY KEY,
  name text NOT NULL,
  unit inventory.unit NOT NULL DEFAULT 'piece',
  price numeric(10, 2) NOT NULL,
  stock bigint NOT NULL DEFAULT 0,
  in_stock boolean NOT NULL DEFAULT true,
  photo bytea,
  supplier_ip inet,
  attributes jsonb NOT NULL DEFAULT '{}'
);

-- No primary or unique key: the grid shows it read-only.
CREATE TABLE inventory.stock_movements (
  sku text NOT NULL REFERENCES inventory.products (sku),
  quantity integer NOT NULL,
  moved_at timestamptz NOT NULL DEFAULT now()
);

