-- Sample database for PostgreSQL. User: app / app-secret, database: shop (owned by app), schemas public and inventory.
-- Runs once, when the container starts with an empty data directory; psql runs it as the postgres superuser.
CREATE ROLE app LOGIN PASSWORD 'app-secret';
CREATE DATABASE shop OWNER app;
CREATE DATABASE analytics OWNER app;

\connect shop app

CREATE TYPE order_status AS ENUM ('pending', 'paid', 'shipped', 'cancelled');
CREATE DOMAIN email_address AS text CHECK (VALUE LIKE '%_@_%');

CREATE TABLE customers (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email email_address NOT NULL UNIQUE,
  tags text[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE customers IS 'People who order';
COMMENT ON COLUMN customers.tags IS 'Free-form labels';

CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  customer_id integer NOT NULL REFERENCES customers (id),
  status order_status NOT NULL DEFAULT 'pending',
  total numeric(12, 2) NOT NULL CHECK (total >= 0),
  details jsonb,
  placed_at timestamptz NOT NULL DEFAULT now(),
  delivery_window interval
);
CREATE INDEX orders_status_idx ON orders (status, placed_at);

CREATE SEQUENCE invoice_number_seq START 1000;

