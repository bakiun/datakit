/**
 * Plays the extension for the table data view (or, with `console`, the query console) on the dev server,
 * with an in-memory `orders` table; `&postgres` shows it as a PostgreSQL table in schema `public`.
 * Queries on `orders` honour a simple `WHERE column = value`, ORDER BY and LIMIT; other writes report one row.
 * A statement containing `fail` fails; a script containing `decline` plays a declined production confirmation.
 * `&initfail` plays a data source that cannot be connected to.
 */
type Row = Record<string, string | null>;

function column(name: string, columnType: string, patch: Partial<ColumnInfo> = {}): ColumnInfo {
  const dataType = columnType.replace(/\(.*$/, '').split(' ')[0]!;
  return {
    name,
    columnType,
    dataType,
    nullable: false,
    defaultValue: null,
    key: '',
    extra: '',
    autoIncrement: false,
    generated: false,
    numeric: ['bigint', 'decimal', 'int'].includes(dataType),
    binary: false,
    enumValues: parseEnumValues(columnType),
    defaultSql: null,
    comment: '',
    charset: ['varchar', 'char', 'enum'].includes(dataType) ? 'utf8mb4' : null,
    collation: ['varchar', 'char', 'enum'].includes(dataType) ? 'utf8mb4_0900_ai_ci' : null,
    onUpdate: null,
    generation: null,
    check: null,
    ...patch,
  };
}

