/** The same table as PostgreSQL describes it. */
function postgresTable(): TableStructure {
  const pg: Record<string, Partial<ColumnInfo>> = {
    id: { columnType: 'bigint', dataType: 'int8', extra: 'GENERATED BY DEFAULT AS IDENTITY', identity: 'by default' },
    customer_email: { columnType: 'character varying(255)' },
    status: { columnType: 'order_status', dataType: 'order_status', defaultValue: "'pending'::order_status", defaultSql: "'pending'::order_status" },
    total: { columnType: 'numeric(12,2)', dataType: 'numeric' },
    currency: { columnType: 'character(3)', dataType: 'bpchar', defaultValue: "'TRY'::bpchar", defaultSql: "'TRY'::bpchar" },
    created_at: { columnType: 'timestamp with time zone', dataType: 'timestamptz', defaultValue: 'now()', defaultSql: 'now()', extra: '' },
    shipped_at: { columnType: 'timestamp with time zone', dataType: 'timestamptz', defaultSql: null },
  };
  return {
    ...structure,
    dialect: 'postgres',
    schema: 'public',
    options: null,
    checks: [{ name: 'orders_total_check', clause: 'total >= 0::numeric' }],
    columns: structure.columns.map((c) => ({ ...c, charset: null, collation: null, identity: null, ...pg[c.name] })),
    indexes: [
      { name: 'orders_pkey', kind: 'PRIMARY', unique: true, columns: ['id'], lengths: [null], constraint: true, method: 'btree', definition: 'CREATE UNIQUE INDEX orders_pkey ON public.orders USING btree (id)' },
      { name: 'orders_status_idx', kind: 'INDEX', unique: false, columns: ['status', 'created_at'], lengths: [null, null], constraint: false, method: 'btree', definition: 'CREATE INDEX orders_status_idx ON public.orders USING btree (status, created_at)' },
    ],
    foreignKeys: structure.foreignKeys.map((f) => ({ ...f, refSchema: 'public', onUpdate: 'NO ACTION' })),
  };
}

function seed(): Row[] {
  const names = ['alice.k', 'm.young', 'jonas.weber', 'sarah.owens', 'c.martin', 'emily.carter', 'hana.sato', 'ben.d'];
  const statuses = ['pending', 'shipped', 'delivered', 'cancelled'];
  const date = (t: number) => new Date(t).toISOString().slice(0, 19).replace('T', ' ');
  let t = Date.UTC(2026, 9, 24, 9, 14, 2);
  return Array.from({ length: 137 }, (_, i) => {
    const id = 1137 - i;
    const h = Math.imul(id, 2654435761) >>> 0;
    const status = statuses[(h >>> 5) % 4]!;
    t -= (4 * 3600 + (h % 7200)) * 1000;
    return {
      id: String(id),
      customer_email: `${names[(h >>> 9) % 8]}@example.com`,
      status,
      total: ((((h >>> 11) % 240000) + 990) / 100).toFixed(2),
      currency: ['TRY', 'EUR', 'USD'][(h >>> 3) % 3]!,
      created_at: date(t),
      shipped_at: status === 'shipped' || status === 'delivered' ? date(t + 72_000_000) : null,
    };
  });
}

export function installTableDataHost(
  reply: (message: TableDataHostMessage, delay?: number) => void,
  asConsole = false,
): (message: TableDataWebviewMessage) => void {
  let rows = seed();
  let saved = rows;
  let nextId = 1138;
  let shown: Row[] = [];
  let open = false;
  let openChanges = 0;
  const params = new URLSearchParams(location.search);
  const readOnly = params.has('readonly');
  const postgres = params.has('postgres');
  const dialect = postgres ? 'postgres' : 'mysql';
  const table = postgres ? postgresTable() : structure;
  const names = table.columns.map((c) => c.name);

  const log = (level: 'info' | 'ok' | 'warning' | 'error', text: string) => reply({ type: 'log', level, text }, 250);

  function select(statement: ScriptStatement, summary?: string): void {
    if (/fail/i.test(statement.text)) {
      reply({ type: 'runFailed', message: "Unknown column 'fail' in 'where clause'", failed: { from: statement.from, to: statement.to } }, 300);
      log('error', "Statement: Unknown column 'fail' in 'where clause'");
      return;
    }
    const paging = readPaging(statement.text, dialect);
    const match = /WHERE\s+(\w+)\s*=\s*'?([^'\s]*)'?/i.exec(statement.text);
    let result = match ? rows.filter((r) => r[match[1]!] === match[2]) : rows;
    result = [...result].sort((a, b) => {
      for (const key of paging.sort ?? []) {
        const numeric = table.columns.find((c) => c.name === key.column)?.numeric;
        const x = a[key.column] ?? '';
        const y = b[key.column] ?? '';
        const order = numeric ? Number(x) - Number(y) : x.localeCompare(y);
        if (order) return key.direction === 'asc' ? order : -order;
      }
      return 0;
    });
    shown = paging.limit === null ? result : result.slice(paging.offset, paging.offset + paging.limit);
    reply(
      {
        type: 'page',
        page: {
          statement,
          columns: table.columns.map((c) => ({ name: c.name, type: c.dataType, numeric: c.numeric, binary: c.binary, column: c })),
          rows: shown.map((r) => names.map((n) => r[n] ?? null)),
          total: statement.unpaged ? result.length : null,
          durationMs: 3.8,
          editable: readOnly ? null : { database: 'shop', ...(postgres ? { schema: 'public' } : {}), table: 'orders', rowKey: ['id'] },
          readOnlyReason: readOnly ? 'The data source is read-only.' : null,
        },
        ...(summary ? { summary } : {}),
      },
      300,
    );
  }

  const transaction = () => reply({ type: 'transaction', open, changes: openChanges });

  return (message) => {
    switch (message.type) {
      case 'ready':
        if (params.has('initfail')) {
          reply({ type: 'initFailed', message: 'Could not connect to “shop-prod”: connect ECONNREFUSED 127.0.0.1:3306', connection: true }, 300);
          break;
        }
        reply({
          type: 'init',
          init: {
            dataSourceName: 'shop-prod',
            environment: 'production',
            serverLabel: postgres ? 'PostgreSQL 17.6' : 'MySQL 8.4.3',
            product: postgres ? 'PostgreSQL' : 'MySQL',
            dialect,
            readOnly,
            structure: asConsole ? null : table,
            console: !asConsole
              ? null
              : postgres
                ? { name: 'console-1.sql', database: 'shop', databases: ['analytics', 'postgres', 'shop'], schema: 'public', schemas: ['public', 'inventory', 'information_schema', 'pg_catalog'] }
                : { name: 'console-1.sql', database: 'shop', databases: ['analytics', 'information_schema', 'shop'] },
            pageSize: 25,
            script: asConsole
              ? (localStorage.getItem('consoleScript') ?? "-- Pending orders\nSELECT *\nFROM orders\nWHERE status = 'pending';")
              : buildSelect(table, { where: '', sort: [{ column: 'id', direction: 'desc' }], limit: 25, offset: 0 }),
            editorHeight: Number(localStorage.getItem(asConsole ? 'consoleHeight' : 'editorHeight')) || null,
            tables: ['customers', 'order_items', 'orders', 'payments', 'products'],
            autoCommit: true,
            exportFormat: (localStorage.getItem('exportFormat') as ExportFormat | null) ?? 'csv',
            exportScope: (localStorage.getItem('exportScope') as ExportScope | null) ?? 'page',
          },
        });
        break;
      case 'run': {
        if (message.statements.some((s) => /decline/i.test(s.text))) {
          reply({ type: 'declined', message: 'Nothing was run.' }, 200);
          break;
        }
        const done: string[] = [];
        let last: ScriptStatement | undefined;
        for (const statement of message.statements) {
          log('ok', `Statement: ${leadingKeyword(statement.text)} (0.0040 s)`);
          if (leadingKeyword(statement.text) === 'SELECT') last = statement;
          else if (changesData(statement.text, dialect)) {
            if (!message.autoCommit) {
              open = true;
              openChanges++;
            }
            done.push(`${leadingKeyword(statement.text)} 1 row affected (0.0042 s)`);
          }
        }
        transaction();
        const summary = message.statements.length > 1 ? `${message.statements.length} statements: ${done.join(' · ')}` : undefined;
        if (last) select(last, summary);
        else reply({ type: 'ran', summary: summary ?? done.join(' · ') }, 200);
        break;
      }
      case 'query':
        select(message.statement);
        break;
      case 'submit': {
        for (const change of message.changes) {
          if (change.kind === 'update') {
            const id = shown[change.row]?.id;
            rows = rows.map((r) => (r.id === id ? { ...r, ...change.values } : r));
          } else if (change.kind === 'delete') {
            const id = shown[change.row]?.id;
            rows = rows.filter((r) => r.id !== id);
          } else {
            const defaults: Row = { status: 'pending', total: '0.00', currency: 'TRY', created_at: '2026-10-24 12:44:00', shipped_at: null };
            rows = [{ ...defaults, customer_email: '', ...change.values, id: String(nextId++) }, ...rows];
          }
        }
        if (message.autoCommit && !open) saved = rows;
        else {
          open = true;
          openChanges += message.changes.length;
        }
        transaction();
        select(message.statement, `${describeChanges(message.changes)} — ${open ? 'not committed yet' : 'committed'} (0.0044 s)`);
        break;
      }
      case 'commit':
      case 'rollback': {
        if (message.type === 'commit') saved = rows;
        else rows = saved;
        const summary = `${message.type === 'commit' ? 'Committed' : 'Rolled back'} ${openChanges} change${openChanges === 1 ? '' : 's'}`;
        open = false;
        openChanges = 0;
        transaction();
        if (message.statement) select(message.statement, summary);
        else reply({ type: 'ran', summary });
        break;
      }
      case 'export':
        localStorage.setItem('exportFormat', message.format);
        localStorage.setItem('exportScope', message.scope);
        reply({ type: 'notice', message: `Saved ${shown.length} rows to orders.${message.format}.` }, 200);
        break;
      case 'copySql':
        reply({ type: 'notice', message: 'Copied the SQL to the clipboard.' });
        break;
      case 'alterTable':
        console.info('[dev host] ALTER TABLE\n' + message.statements.join(';\n'));
        if (message.statements.some((statement) => /fail/i.test(statement))) {
          reply({ type: 'alterFailed', message: "Unknown column 'fail' (dev host)" }, 400);
        } else reply({ type: 'structure', structure: table, summary: 'Table changed (dev host: nothing was really changed).' }, 400);
        break;
      case 'editorHeight':
        localStorage.setItem(asConsole ? 'consoleHeight' : 'editorHeight', String(message.height));
        break;
      case 'script':
        localStorage.setItem('consoleScript', message.script);
        break;
      case 'useDatabase': {
        const tables = message.database === 'shop' ? ['customers', 'orders'] : ['events', 'sessions'];
        const schemas = postgres ? { schema: 'public', schemas: ['public', 'information_schema', 'pg_catalog'] } : {};
        reply({ type: 'database', database: message.database, tables, ...schemas }, 150);
        log('info', `Using database ${message.database}.`);
        break;
      }
      case 'useSchema':
        reply({ type: 'database', database: 'shop', tables: message.schema === 'inventory' ? ['products'] : ['customers', 'orders'], schema: message.schema, schemas: ['public', 'inventory', 'information_schema', 'pg_catalog'] }, 150);
        log('info', `Using schema ${message.schema}.`);
        break;
      case 'explain':
        if (/fail/i.test(message.statement)) reply({ type: 'planFailed', message: 'You have an error in your SQL syntax (dev host)' }, 200);
        else if (postgres) {
          const column = { name: 'QUERY PLAN', type: 'text', numeric: false, binary: false, column: null };
          const plan = message.analyze
            ? [
                'Seq Scan on orders  (cost=0.00..3.71 rows=34 width=64) (actual time=0.010..0.031 rows=34 loops=1)',
                "  Filter: (status = 'pending'::order_status)",
                '  Rows Removed by Filter: 103',
                'Planning Time: 0.061 ms',
                'Execution Time: 0.052 ms',
              ]
            : ['Seq Scan on orders  (cost=0.00..3.71 rows=34 width=64)', "  Filter: (status = 'pending'::order_status)"];
          reply({ type: 'plan', statement: message.statement, columns: [column], rows: plan.map((line) => [line]) }, 200);
        } else {
          const columns = ['id', 'select_type', 'table', 'type', 'key', 'rows', 'Extra'].map((name) => ({
            name,
            type: name === 'id' || name === 'rows' ? 'bigint' : 'varchar',
            numeric: name === 'id' || name === 'rows',
            binary: false,
            column: null,
          }));
          reply({ type: 'plan', statement: message.statement, columns, rows: [[1, 'SIMPLE', 'orders', 'ALL', null, rows.length, 'Using where']] }, 200);
        }
        break;
      case 'openConsole':
        console.info('[dev host] open in console\n' + message.script);
        break;
      case 'stop':
      case 'viewDdl':
      case 'txMode':
      case 'pageSize':
      case 'editDataSource':
        console.info('[dev host]', message.type);
        break;
    }
  };
}
